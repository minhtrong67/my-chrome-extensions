/**
 * generate-palettes.mjs
 * Builds css/palettes.css: one Material Design 3 colour scheme (light + dark)
 * for every Material "500" swatch, using Google's official
 * @material/material-color-utilities (Vibrant scheme so the swatch stays recognisable; low-chroma
 * seeds such as brown / blue-grey use the Content scheme). Run with: npm run generate
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

// The package ships extension-less ESM imports that Node cannot resolve, so
// load its CommonJS build instead.
const require = createRequire(import.meta.url);
const {
  argbFromHex, hexFromArgb, Hct, SchemeVibrant, SchemeContent, MaterialDynamicColors: M
} = require("@material/material-color-utilities");

export const COLORS = {
  red: "#F44336", pink: "#E91E63", purple: "#9C27B0", deepPurple: "#673AB7",
  indigo: "#3F51B5", blue: "#2196F3", lightBlue: "#03A9F4", cyan: "#00BCD4",
  teal: "#009688", green: "#4CAF50", lightGreen: "#8BC34A", lime: "#CDDC39",
  yellow: "#FFEB3B", amber: "#FFC107", orange: "#FF9800", deepOrange: "#FF5722",
  brown: "#795548", blueGrey: "#607D8B"
};

const ROLES = {
  "primary": M.primary, "on-primary": M.onPrimary,
  "primary-container": M.primaryContainer, "on-primary-container": M.onPrimaryContainer,
  "secondary": M.secondary, "on-secondary-container": M.onSecondaryContainer,
  "secondary-container": M.secondaryContainer,
  "error": M.error, "on-error": M.onError,
  "error-container": M.errorContainer, "on-error-container": M.onErrorContainer,
  "surface": M.surface, "on-surface": M.onSurface, "on-surface-variant": M.onSurfaceVariant,
  "outline": M.outline, "outline-variant": M.outlineVariant,
  "surface-container-lowest": M.surfaceContainerLowest,
  "surface-container-low": M.surfaceContainerLow,
  "surface-container": M.surfaceContainer,
  "surface-container-high": M.surfaceContainerHigh,
  "surface-container-highest": M.surfaceContainerHighest,
  "inverse-surface": M.inverseSurface, "inverse-on-surface": M.inverseOnSurface,
  "inverse-primary": M.inversePrimary
};

function block(selector, scheme) {
  const vars = Object.entries(ROLES)
    .map(([name, role]) => `--md-sys-color-${name}:${hexFromArgb(role.getArgb(scheme)).toLowerCase()}`)
    .join(";");
  return `${selector}{${vars}}`;
}

const NEUTRAL_SEEDS = new Set(["brown", "blueGrey"]);

export function schemeCss(id, hex) {
  const hct = Hct.fromInt(argbFromHex(hex));
  const Scheme = NEUTRAL_SEEDS.has(id) ? SchemeContent : SchemeVibrant;
  return [
    block(`[data-color="${id}"][data-theme="light"]`, new Scheme(hct, false, 0)),
    block(`[data-color="${id}"][data-theme="dark"]`, new Scheme(hct, true, 0))
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const css = "/* AUTO-GENERATED by scripts/generate-palettes.mjs — do not edit by hand. */\n" +
    Object.entries(COLORS).map(([id, hex]) => schemeCss(id, hex)).join("\n") + "\n";
  writeFileSync(new URL("../css/palettes.css", import.meta.url), css);
  console.log("palettes.css:", css.length, "bytes");
}
