/**
 * generate-icons.mjs
 * Reads the Lucide SVGs the UI uses and writes js/icons.js — a tiny registry
 * (name -> inner SVG markup) plus a hydrate() helper. No runtime network, no
 * icon font. Run with: npm run generate
 */
import { readFileSync, writeFileSync } from "node:fs";

const USED = [
  "layout-grid", "settings", "sun", "moon", "monitor", "languages", "palette", "type",
  "download", "upload", "rotate-ccw", "info", "keyboard", "external-link", "git-branch",
  "shield-check", "zap", "eye-off", "minimize-2", "message-square-off", "focus",
  "panel-right-close", "check", "heart", "sliders-horizontal", "circle-check", "x",
  "power", "database", "square-play", "scale", "text-cursor-input", "globe", "code-xml",
  "triangle-alert", "play", "refresh-cw", "arrow-left"
];

const inner = (svg) => svg
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .replace(/\s*\n\s*/g, "")
  .trim();

const map = {};
for (const name of USED) {
  map[name] = inner(readFileSync(`node_modules/lucide-static/icons/${name}.svg`, "utf8"));
}

const out = `/**
 * icons.js — Lucide icons (https://lucide.dev, ISC licence), inlined.
 * AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.
 * Usage: <i data-icon="settings"></i>  then  Icons.hydrate(root)
 */
(() => {
  const PATHS = ${JSON.stringify(map)};

  function svg(name, size) {
    const body = PATHS[name];
    if (!body) return "";
    const s = size ? \` width="\${size}" height="\${size}"\` : "";
    return \`<svg class="icon" xmlns="http://www.w3.org/2000/svg"\${s} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${body}</svg>\`;
  }

  /** Replace every <i data-icon="name"> under root with its inline SVG. */
  function hydrate(root = document) {
    root.querySelectorAll("i[data-icon]").forEach((el) => {
      const html = svg(el.dataset.icon, el.dataset.size);
      if (!html) return;
      const tpl = document.createElement("template");
      tpl.innerHTML = html;
      const node = tpl.content.firstElementChild;
      el.classList.forEach((c) => node.classList.add(c));
      el.replaceWith(node);
    });
  }

  window.Icons = { svg, hydrate };
})();
`;
writeFileSync(new URL("../js/icons.js", import.meta.url), out);
console.log("icons.js:", out.length, "bytes,", USED.length, "icons");
