/** "system" → the device language (Vietnamese or English). */
function resolveLang(pref) {
  if (pref === "vi" || pref === "en") return pref;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  return String(nav).toLowerCase().startsWith("vi") ? "vi" : "en";
}

/** Returns a translate function t(key, ...args) for a language. */
function makeT(lang) {
  const dict = I18N[lang] || I18N.en;
  return (key, ...args) => {
    const v = dict[key] !== undefined ? dict[key] : I18N.en[key];
    if (typeof v === "function") return v(...args);
    return v !== undefined ? v : key;
  };
}
