// Generates css/themes.css — Material Design 3 colour roles for every
// Material palette colour, in light and dark. Run: npm run build:themes
import { writeFileSync } from "node:fs";
import {
  themeFromSourceColor, argbFromHex, hexFromArgb
} from "@material/material-color-utilities";

// Official Material Design (2014 palette) 500-tones used as seed colours.
export const ACCENTS = {
  red: "#F44336", pink: "#E91E63", purple: "#9C27B0", deepPurple: "#673AB7",
  indigo: "#3F51B5", blue: "#2196F3", lightBlue: "#03A9F4", cyan: "#00BCD4",
  teal: "#009688", green: "#4CAF50", lightGreen: "#8BC34A", lime: "#CDDC39",
  yellow: "#FFEB3B", amber: "#FFC107", orange: "#FF9800", deepOrange: "#FF5722",
  brown: "#795548", grey: "#9E9E9E", blueGrey: "#607D8B"
};

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "background", "onBackground", "surface", "onSurface",
  "surfaceVariant", "onSurfaceVariant", "outline", "outlineVariant",
  "inverseSurface", "inverseOnSurface", "inversePrimary"
];
const SURFACE_TONES = {
  light: { dim: 87, bright: 98, lowest: 100, low: 96, container: 94, high: 92, highest: 90 },
  dark:  { dim: 6,  bright: 24, lowest: 4,   low: 10, container: 12, high: 17, highest: 22 }
};

function block(selector, theme, mode) {
  const s = theme.schemes[mode].toJSON();
  const lines = ROLES.map((r) => `  --md-${kebab(r)}: ${hexFromArgb(s[r])};`);
  const n = theme.palettes.neutral;
  for (const [k, tone] of Object.entries(SURFACE_TONES[mode])) {
    const name = k === "dim" || k === "bright" ? `surface-${k}` : `surface-container${k === "container" ? "" : "-" + k}`;
    lines.push(`  --md-${name}: ${hexFromArgb(n.tone(tone))};`);
  }
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

let css = "/* AUTO-GENERATED by scripts/build-themes.mjs — do not edit by hand. */\n";
css += "/* Material Design 3 colour roles for every Material palette colour. */\n\n";
for (const [name, hex] of Object.entries(ACCENTS)) {
  const theme = themeFromSourceColor(argbFromHex(hex));
  css += block(`[data-theme="light"][data-accent="${name}"]`, theme, "light");
  css += block(`[data-theme="dark"][data-accent="${name}"]`, theme, "dark");
}
writeFileSync("css/themes.css", css);
writeFileSync("js/accents.js",
`// AUTO-GENERATED by scripts/build-themes.mjs — do not edit by hand.
const ACCENT_COLORS = ${JSON.stringify(ACCENTS, null, 2)};
`);
console.log("themes.css + accents.js written for", Object.keys(ACCENTS).length, "colours");
