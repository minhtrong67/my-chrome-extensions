// Generates js/lucide.js — a tiny inline sprite of the Lucide icons used by the UI.
// (Extensions can't load icons from a CDN under MV3's CSP, so they are bundled.)
// Run: npm run build:lucide
import { readFileSync, writeFileSync } from "node:fs";

const USED = [
  "camera", "settings", "sun", "moon", "monitor", "arrow-left", "x", "scan",
  "scroll-text", "crop", "history", "trash-2", "palette", "type", "languages",
  "image", "sliders-horizontal", "download", "upload", "rotate-ccw", "info",
  "heart", "check", "chevron-down", "triangle-alert", "mouse-pointer-2",
  "pencil", "move-up-right", "square", "circle", "highlighter", "grid-3x3",
  "undo-2", "redo-2", "copy", "zoom-in", "zoom-out", "maximize", "save",
  "clock", "file-image", "external-link", "github", "keyboard", "text-cursor-input",
  "eraser", "layers", "shield-check", "zap", "lock", "globe", "puzzle", "folder-down",
  "sparkles", "code-xml", "scale", "bot", "menu", "ban"
];
const dir = "node_modules/lucide-static/icons/";
const out = {};
const missing = [];
for (const name of USED) {
  try {
    const svg = readFileSync(dir + name + ".svg", "utf8");
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "");
    out[name] = inner;
  } catch { missing.push(name); }
}
if (missing.length) console.warn("Missing lucide icons:", missing.join(", "));

writeFileSync("js/lucide.js",
`// AUTO-GENERATED by scripts/build-lucide.mjs — Lucide icons (ISC licence), https://lucide.dev
const LUCIDE_ICONS = ${JSON.stringify(out)};

const lucide = {
  svg(name, size) {
    const inner = LUCIDE_ICONS[name];
    if (!inner) return "";
    const s = size || 20;
    return '<svg class="lucide" xmlns="http://www.w3.org/2000/svg" width="' + s + '" height="' + s +
      '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"' +
      ' stroke-linejoin="round" aria-hidden="true" focusable="false">' + inner + "</svg>";
  },
  // Replace every <i data-lucide="name" data-size="20"></i> inside root with its SVG.
  render(root) {
    (root || document).querySelectorAll("[data-lucide]").forEach((node) => {
      const name = node.getAttribute("data-lucide");
      const size = parseInt(node.getAttribute("data-size") || "20", 10);
      const html = this.svg(name, size);
      if (!html) return;
      node.insertAdjacentHTML("afterend", html);
      const svg = node.nextElementSibling;
      node.classList.forEach((c) => svg.classList.add(c));
      node.remove();
    });
  }
};
`);
console.log("lucide.js written with", Object.keys(out).length, "icons");
