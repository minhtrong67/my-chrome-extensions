  DD.makeT = (lang) => {
    const dict = S[lang] || S.en;
    return (key, vars) => {
      let s = dict[key] ?? S.en[key] ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : vars[k]));
      return s;
    };
  };

  DD.colorLabel = (lang, name) => (lang === 'vi' ? DD.COLOR_NAMES_VI[name] || name : name);

  DD.applyI18n = (t, root = document) => {
    root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n, el._vars)));
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const v = t(el.dataset.i18nTitle);
      el.title = v;
      el.setAttribute('aria-label', v);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
    document.documentElement.lang = t === null ? 'en' : document.documentElement.lang;
  };
