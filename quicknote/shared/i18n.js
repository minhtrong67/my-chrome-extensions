  function t(lang, key, ...args) {
    const entry = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    return typeof entry === 'function' ? entry(...args) : entry;
  }

  function apply(lang, root) {
    const scope = root || document;
    scope.documentElement && (scope.documentElement.lang = lang);
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(lang, el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const v = t(lang, el.dataset.i18nTitle);
      el.title = v;
      el.setAttribute('aria-label', v);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(lang, el.dataset.i18nPlaceholder); });
  }

